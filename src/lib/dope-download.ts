import type { DopeResult, UserProfile } from "@/lib/hr-types";
import { DOPE_QUESTIONS, DOPE_PERSONALITY_TYPES } from "@/lib/hr-constants";
import { fmtDate, fmtTime } from "@/lib/hr-store";

export function downloadDopeResult(profile: UserProfile, result: DopeResult) {
  const typeMeta = DOPE_PERSONALITY_TYPES[result.personalityType];
  const lines: string[] = [];

  lines.push("============================================");
  lines.push("   YES EMPIRE GROUP — ELEVATE SYSTEM");
  lines.push("   DOPE PERSONALITY TEST — RESULT");
  lines.push("============================================");
  lines.push("");
  lines.push(`Staff Name  : ${profile.fullName}`);
  lines.push(`Username    : ${profile.username}`);
  lines.push(`Position    : ${profile.role}`);
  lines.push(`Test Date   : ${fmtDate(result.date)} ${fmtTime(result.date)}`);
  lines.push(`Status      : ${result.status}`);
  lines.push("");
  lines.push("--------------------------------------------");
  lines.push("PERSONALITY TYPE");
  lines.push("--------------------------------------------");
  lines.push(typeMeta?.label || result.personalityType);
  lines.push("");
  lines.push(result.summary || typeMeta?.summary || "");
  lines.push("");
  lines.push("--------------------------------------------");
  lines.push("PERSONALITY TRAIT SCORES");
  lines.push("--------------------------------------------");
  Object.entries(result.scores).forEach(([trait, score]) => {
    const bar =
      "█".repeat(Math.min(score, 15)) + "░".repeat(Math.max(0, 15 - score));
    lines.push(`${trait.padEnd(18)} ${bar} ${score}`);
  });
  lines.push("");
  lines.push("--------------------------------------------");
  lines.push("QUESTION ANSWERS");
  lines.push("--------------------------------------------");
  result.answers.forEach((ans, i) => {
    const q = DOPE_QUESTIONS.find((qq) => qq.id === ans.questionId);
    const opt = q?.options.find((o) => o.id === ans.optionId);
    lines.push(`${i + 1}. ${q?.text || ""}`);
    lines.push(`   Answer: ${opt?.text || ""}`);
    lines.push("");
  });
  lines.push("============================================");
  lines.push("This document was generated by the YES EMPIRE HR System.");
  lines.push("This test result is private and confidential.");
  lines.push("============================================");

  const content = lines.join("\n");
  const blob = new Blob([content], { type: "text/plain;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = `Dope-Personality-Test-${profile.username}-${result.date}.txt`;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
